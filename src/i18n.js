const DICTS = { sv, en };
let lang = 'sv';

export function detectLang() {
  const l = (typeof navigator !== 'undefined' && (navigator.languages?.[0] || navigator.language)) || 'sv';
  return /^(sv|nb|nn|no|da)/i.test(l) ? 'sv' : 'en';
}
export function setLang(pref) { lang = pref === 'sv' || pref === 'en' ? pref : detectLang(); document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function t(key, ...args) {
  const v = DICTS[lang][key] ?? sv[key];
  return typeof v === 'function' ? v(...args) : v ?? key;
}
export function fmtDate(iso, withYear = false) {
  const d = iso ? new Date(iso) : new Date();
  return `${d.getDate()} ${t('months')[d.getMonth()]}${withYear ? ' ' + d.getFullYear() : ''}`;
}
export const fmtDateLower = (iso) => fmtDate(iso).toLowerCase();
